"""Regenerates src/data/htmlentities.ts from CPython's html and html.entities modules."""
import html
import html.entities
import json
import sys

# Only alphanumeric names ending in ';', since parser/flowchart.py matches `#([A-Za-z0-9]+);`
# and looks up `html.entities.html5.get(f"{code};", ...)`.
named = {
    k[:-1]: v
    for k, v in sorted(html.entities.html5.items())
    if k.endswith(";") and k[:-1].isalnum()
}

invalid_charrefs = {int(k): v for k, v in sorted(html._invalid_charrefs.items())}
invalid_codepoints = sorted(html._invalid_codepoints)

print(f"""// GENERATED by scripts/htmlentities.py from CPython {sys.version.split()[0]}.
// Do not edit by hand: rerun `python3 scripts/htmlentities.py > src/data/htmlentities.ts`.

const HTML5_NAMED: Readonly<Record<string, string>> = {json.dumps(named, ensure_ascii=False, indent=2)};

const INVALID_CHARREFS: ReadonlyMap<number, string> = new Map({json.dumps(list(invalid_charrefs.items()), ensure_ascii=False)});

const INVALID_CODEPOINTS: ReadonlySet<number> = new Set({json.dumps(invalid_codepoints)});

/** Lookup `html.entities.html5.get(code + ";")`. */
export function lookupHtml5Entity(code: string): string | undefined {{
  return Object.prototype.hasOwnProperty.call(HTML5_NAMED, code) ? HTML5_NAMED[code] : undefined;
}}

/** CPython's `html.unescape(f"&#{{code}};")` for an ASCII digit string `code`. */
export function decodeDecimalCharRef(digits: string): string {{
  const big = BigInt(digits);
  if (big > 0x10ffffn) return "\\uFFFD";
  const num = Number(big);
  const mapped = INVALID_CHARREFS.get(num);
  if (mapped !== undefined) return mapped;
  if (num >= 0xd800 && num <= 0xdfff) return "\\uFFFD";
  if (INVALID_CODEPOINTS.has(num)) return "";
  return String.fromCodePoint(num);
}}""")
